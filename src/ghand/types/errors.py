    POSITION_SENSOR_UNCALIBRATED_MF3 = 1 << 34
    POSITION_SENSOR_UNCALIBRATED_RF2 = 1 << 35
    POSITION_SENSOR_UNCALIBRATED_RF3 = 1 << 36
    POSITION_SENSOR_UNCALIBRATED_LF2 = 1 << 37
    POSITION_SENSOR_UNCALIBRATED_LF3 = 1 << 38

    # Stalled joints during zeroing: bits 39..51.
    ZEROING_JOINT_STALL_THUMB2 = 1 << 39
    ZEROING_JOINT_STALL_THUMB3 = 1 << 40
    ZEROING_JOINT_STALL_THUMB4 = 1 << 41
    ZEROING_JOINT_STALL_THUMB5 = 1 << 42
    ZEROING_JOINT_STALL_FF2 = 1 << 43
    ZEROING_JOINT_STALL_FF3 = 1 << 44
    ZEROING_JOINT_STALL_FF4 = 1 << 45
