    POSITION_SENSOR_ABNORMAL_FF3 = 1 << 18
    POSITION_SENSOR_ABNORMAL_FF4 = 1 << 19
    POSITION_SENSOR_ABNORMAL_MF2 = 1 << 20
    POSITION_SENSOR_ABNORMAL_MF3 = 1 << 21
    POSITION_SENSOR_ABNORMAL_RF2 = 1 << 22
    POSITION_SENSOR_ABNORMAL_RF3 = 1 << 23
    POSITION_SENSOR_ABNORMAL_LF2 = 1 << 24
    POSITION_SENSOR_ABNORMAL_LF3 = 1 << 25

